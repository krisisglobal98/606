/**
 * Read-only access to external source databases.
 *
 * PostgreSQL:
 * - One pg.Pool per configured connection, created lazily and reused (never a connection per request).
 * - Every statement runs inside `BEGIN READ ONLY` with `SET LOCAL statement_timeout`, and every session
 *   starts with `default_transaction_read_only = on`. A write therefore fails in PostgreSQL itself,
 *   even if the account happens to have write privileges.
 * - A query whose HTTP request was aborted is cancelled on the server with pg_cancel_backend.
 *
 * ClickHouse (HTTP interface):
 * - One client per connection with a bounded keep-alive socket pool (max_open_connections).
 * - Every statement carries `readonly=2` (writes rejected by ClickHouse, settings still allowed) and
 *   `max_execution_time`; an aborted request is cancelled on the server
 *   (`cancel_http_readonly_queries_on_client_close`).
 *
 * Only SQL generated by DOD reaches this class, and it must start with SELECT / WITH / SHOW.
 *
 * MySQL, MongoDB and Redis have their own drivers (see *MetadataService.ts); they take their
 * password from `secret()` here and register a reset hook so a failed test drops their clients too.
 *
 * Connections and passwords come only from the server environment (DOD_DW_CONNECTIONS, DOD_DW_<P>_*,
 * DOD_DW_<P>_PASSWORD in .env); a connection without its password is "not configured" and is never
 * dialled.
 */
import { createClient, type ClickHouseClient, type ClickHouseSettings } from '@clickhouse/client'
import pg from 'pg'
import { readSecret, type Config, type SourceConnectionConfig } from '../config/config.ts'
import { rollback } from '../db/connection.ts'
import { AppError, sourceError, toSourceError } from '../http/errors.ts'
import type { Logger } from '../log/logger.ts'
import type { QueryLog } from '../log/queryLog.ts'

export interface RunOptions {
  /** Query kind for metrics, e.g. "preview", "analytics.main". */
  kind: string
  timeoutMs: number
  signal?: AbortSignal
  datasetId?: string | null
  userId?: string | null
  /**
   * The statement was written by the user (Laporan Excel, Query Data): a PostgreSQL error in the statement itself
   * (class 42 syntax/name, 22 data) is reported with its message and position so the editor can show it. Every
   * other error (connection, authentication, server) is classified without details, as always.
   */
  sqlErrors?: boolean
}

export interface RunResult<R> {
  rows: R[]
  /** Result columns with the source's type (PostgreSQL type OID or ClickHouse type name). */
  fields: { name: string; type: number | string }[]
  durationMs: number
}

const READ_ONLY_SQL = /^\s*(SELECT|WITH|SHOW)\b/i
const WRITE_KEYWORDS = /\b(INSERT|UPDATE|DELETE|MERGE|ALTER|DROP|TRUNCATE|CREATE|GRANT|REVOKE|COPY|VACUUM|REINDEX|CLUSTER|REFRESH)\b/i

/** Defence in depth: rejects anything that is not a single read statement. */
export function assertReadOnlySql(sql: string) {
  const stripped = sql.replace(/'(?:[^']|'')*'/g, "''").replace(/"(?:[^"]|"")*"/g, '""')
  if (!READ_ONLY_SQL.test(stripped) || WRITE_KEYWORDS.test(stripped) || stripped.includes(';')) throw sourceError('SOURCE_READ_ONLY_VIOLATION', 'non-read statement blocked')
}

/**
 * Source values are returned as the database holds them: `timestamp`/`date` stay wall-clock strings
 * (no shift into the server's time zone) and int8 becomes a number when it is safely representable.
 */
const SOURCE_TYPES = {
  getTypeParser(oid: number, format?: 'text' | 'binary') {
    if (oid === 1114 || oid === 1082) return (v: string) => v
    if (oid === 20) return (v: string) => (Number.isSafeInteger(Number(v)) ? Number(v) : v)
    return pg.types.getTypeParser(oid, format)
  },
} as pg.CustomTypesConfig

/**
 * Session settings for every ClickHouse statement DOD sends. NULL semantics follow PostgreSQL so the
 * same generated statements (GROUPING SETS rollups, FULL JOIN of actual/budget) behave identically.
 */
const CH_SETTINGS: ClickHouseSettings = {
  readonly: '2',
  cancel_http_readonly_queries_on_client_close: 1,
  group_by_use_nulls: 1,
  join_use_nulls: 1,
  // 64-bit integers arrive as strings and are converted when safely representable (as for PostgreSQL int8).
  output_format_json_quote_64bit_integers: 1,
}

/** ClickHouse's server keep-alive is 30 s by default; an idle socket must be dropped before the server does. */
const CH_MAX_IDLE_SOCKET_MS = 25_000

const INT64 = /^(Nullable\()?(LowCardinality\()?U?Int(64|128|256)\b/
/** How long a PostgreSQL connection that failed to connect answers with that failure instead of reconnecting. */
const CONNECT_BACKOFF_MS = 20_000
const PASSWORD_REQUIRED = new Set(['postgresql', 'clickhouse', 'mysql'])

type Row = Record<string, unknown>

export class SourceRegistry {
  private readonly pools = new Map<string, pg.Pool>()
  /** Connections that failed to connect, until when they are not retried (see runPostgres). */
  private readonly down = new Map<string, { until: number; err: unknown }>()
  private readonly clickhouse = new Map<string, ClickHouseClient>()
  private readonly resetHooks: ((id: string) => Promise<void>)[] = []
  private readonly config: Config
  private readonly log: Logger
  private readonly queryLog: QueryLog

  constructor(config: Config, log: Logger, queryLog: QueryLog) {
    this.config = config
    this.log = log
    this.queryLog = queryLog
  }

  /** The connections of .env (DOD_DW_CONNECTIONS); DOD Minimal has no other kind. */
  list(): SourceConnectionConfig[] {
    return this.config.connections
  }

  get(id: string): SourceConnectionConfig | undefined {
    return this.list().find((c) => c.id === id)
  }

  /**
   * Why the connection cannot be used right now, known without connecting: not configured, or it failed to connect
   * a moment ago (still in its back-off). null when nothing is known against it.
   */
  knownFailure(id: string): AppError | null {
    const c = this.get(id)
    if (!c) return sourceError('SOURCE_NOT_CONFIGURED', 'connection not in DOD_DW_CONNECTIONS')
    if (!this.isConfigured(c)) return sourceError('SOURCE_NOT_CONFIGURED', `missing ${c.passwordSecret}`)
    const d = this.down.get(id)
    return d && d.until > Date.now() && d.err instanceof AppError ? d.err : null
  }

  /** A driver's way to drop its clients when a connection is reset. */
  onReset(hook: (id: string) => Promise<void>) {
    this.resetHooks.push(hook)
  }

  /** The connection's password (DOD_DW_<P>_PASSWORD), read at the moment a client opens. */
  secret(c: SourceConnectionConfig): string | null {
    return readSecret(c.passwordSecret)
  }

  /** PostgreSQL, ClickHouse and MySQL need DOD_DW_<P>_PASSWORD; Redis/MongoDB may run without AUTH. */
  isConfigured(c: SourceConnectionConfig) {
    return !PASSWORD_REQUIRED.has(c.dbType) || readSecret(c.passwordSecret) != null
  }

  /** Password for drivers that require one; a missing secret is reported as not configured, without connecting. */
  private required(c: SourceConnectionConfig): string {
    const p = this.secret(c)
    if (p == null && PASSWORD_REQUIRED.has(c.dbType)) throw sourceError('SOURCE_NOT_CONFIGURED', `missing ${c.passwordSecret}`)
    return p ?? ''
  }

  private pool(c: SourceConnectionConfig): pg.Pool {
    let p = this.pools.get(c.id)
    if (p) return p
    const password = this.required(c)
    p = new pg.Pool({
      host: c.host,
      port: c.port,
      database: c.database,
      user: c.username,
      password,
      ssl: c.sslMode === 'disable' ? false : c.sslMode === 'require' ? { rejectUnauthorized: false } : { rejectUnauthorized: true, ca: c.sslRootCert ?? undefined, servername: c.host },
      min: c.pool.min,
      max: c.pool.max,
      idleTimeoutMillis: c.pool.idleTimeoutMs,
      connectionTimeoutMillis: c.connectTimeoutMs,
      // Hard client-side ceiling in case the server never answers (network partition).
      query_timeout: Math.max(c.commandTimeoutMs, this.config.limits.analyticsTimeoutMs) + 10_000,
      application_name: 'dod-dw',
      options: `-c default_transaction_read_only=on -c statement_timeout=${c.commandTimeoutMs}`,
      keepAlive: true,
      types: SOURCE_TYPES,
    })
    p.on('error', (e) => this.log.warn({ connection: c.id, code: (e as { code?: string }).code }, 'source idle client error'))
    this.pools.set(c.id, p)
    return p
  }

  private chClient(c: SourceConnectionConfig): ClickHouseClient {
    let client = this.clickhouse.get(c.id)
    if (client) return client
    const password = this.required(c)
    client = createClient({
      url: `${c.protocol}://${c.host}:${c.port}`,
      username: c.username,
      password,
      database: c.database,
      application: 'dod-dw',
      max_open_connections: c.pool.max,
      // Hard client-side ceiling in case the server never answers (network partition).
      request_timeout: Math.max(c.commandTimeoutMs, this.config.limits.analyticsTimeoutMs) + 10_000,
      keep_alive: { enabled: true, idle_socket_ttl: Math.min(c.pool.idleTimeoutMs, CH_MAX_IDLE_SOCKET_MS) },
      clickhouse_settings: CH_SETTINGS,
    })
    this.clickhouse.set(c.id, client)
    return client
  }

  poolStats(id: string) {
    const p = this.pools.get(id)
    // The ClickHouse client does not expose socket counts; its pool is reported as not inspected.
    return p ? { total: p.totalCount, idle: p.idleCount, waiting: p.waitingCount, max: this.get(id)?.pool.max ?? this.config.pool.max } : null
  }

  /** Runs one generated read statement with parameters, a timeout and cancellation. */
  async run<R extends Row = Row>(c: SourceConnectionConfig, sql: string, values: unknown[], o: RunOptions): Promise<RunResult<R>> {
    assertReadOnlySql(sql)
    if (c.dbType !== 'postgresql' && c.dbType !== 'clickhouse') throw new Error(`SQL engine not available for ${c.dbType}`)
    return c.dbType === 'clickhouse' ? this.runClickHouse<R>(c, sql, values, o) : this.runPostgres<R>(c, sql, values, o)
  }

  private async runClickHouse<R extends Row>(c: SourceConnectionConfig, sql: string, values: unknown[], o: RunOptions): Promise<RunResult<R>> {
    const started = new Date()
    const t0 = performance.now()
    const params = Object.fromEntries(values.map((v, i) => [`p${i + 1}`, v]))
    try {
      if (o.signal?.aborted) throw new DOMException('Aborted', 'AbortError')
      const rs = await this.chClient(c).query({
        query: sql,
        format: 'JSON',
        query_params: params,
        abort_signal: o.signal,
        clickhouse_settings: { max_execution_time: Math.max(1, Math.ceil(o.timeoutMs / 1000)) },
      })
      const body = await rs.json<Row>()
      const meta = body.meta ?? []
      const ints = meta.filter((m) => INT64.test(m.type)).map((m) => m.name)
      const rows = body.data.map((r) => {
        for (const k of ints) {
          const v = r[k]
          if (typeof v === 'string' && Number.isSafeInteger(Number(v))) r[k] = Number(v)
        }
        return r as R
      })
      const durationMs = Math.round(performance.now() - t0)
      this.queryLog.record({ started, durationMs, connectionId: c.id, datasetId: o.datasetId ?? null, userId: o.userId ?? null, kind: o.kind, status: 'ok', rows: rows.length, errorCode: null })
      return { rows, fields: meta.map((m) => ({ name: m.name, type: m.type })), durationMs }
    } catch (e) {
      const durationMs = Math.round(performance.now() - t0)
      const aborted = o.signal?.aborted === true || (e instanceof Error && e.name === 'AbortError')
      const err = aborted ? null : toSourceError(e)
      this.queryLog.record({ started, durationMs, connectionId: c.id, datasetId: o.datasetId ?? null, userId: o.userId ?? null, kind: o.kind, status: aborted ? 'cancelled' : 'error', rows: null, errorCode: err?.code ?? 'CLIENT_ABORTED' })
      if (err) this.log.warn({ connection: c.id, kind: o.kind, durationMs, code: err.code, diagnostic: err.diagnostic }, 'source query failed')
      else this.log.info({ connection: c.id, kind: o.kind }, 'source query cancelled (client aborted)')
      throw err ?? e
    }
  }

  private async runPostgres<R extends Row>(c: SourceConnectionConfig, sql: string, values: unknown[], o: RunOptions): Promise<RunResult<R>> {
    const started = new Date()
    const t0 = performance.now()
    // A connection that just failed to connect is not retried for a moment: the same error is returned at once.
    // Otherwise every page load (coverage and values of many datasets) turns into a storm of failing connection
    // attempts; on Windows each one starts a server process, and the server answers "too many clients" (53300)
    // to everyone, including other applications on the same PostgreSQL.
    const down = this.down.get(c.id)
    if (down && down.until > Date.now()) throw down.err
    let client: pg.PoolClient | null = null
    let broken: Error | undefined
    let cancelled = false
    const onAbort = () => {
      cancelled = true
      const pid = (client as unknown as { processID?: number } | null)?.processID
      if (pid) void this.cancelBackend(c, pid)
    }
    try {
      if (o.signal?.aborted) throw new DOMException('Aborted', 'AbortError')
      client = await this.pool(c).connect()
      o.signal?.addEventListener('abort', onAbort, { once: true })
      await client.query('BEGIN READ ONLY')
      await client.query(`SET LOCAL statement_timeout = ${Math.max(1000, Math.round(o.timeoutMs))}`)
      const res = await client.query<R & pg.QueryResultRow>({ text: sql, values })
      await client.query('COMMIT')
      const durationMs = Math.round(performance.now() - t0)
      this.queryLog.record({ started, durationMs, connectionId: c.id, datasetId: o.datasetId ?? null, userId: o.userId ?? null, kind: o.kind, status: 'ok', rows: res.rowCount ?? res.rows.length, errorCode: null })
      return { rows: res.rows, fields: res.fields.map((f) => ({ name: f.name, type: f.dataTypeID })), durationMs }
    } catch (e) {
      // A cancelled or failed statement leaves a healthy session (rolled back, back to the pool); a broken connection
      // or a failed ROLLBACK destroys the client instead.
      if (client) broken = await rollback(client, e)
      const durationMs = Math.round(performance.now() - t0)
      const aborted = cancelled || (e instanceof DOMException && e.name === 'AbortError')
      const pgCode = String((e as { code?: unknown }).code ?? '')
      const own = !aborted && o.sqlErrors && /^(42|22)/.test(pgCode)
      const err = aborted ? null : own ? new AppError(422, 'SOURCE_SQL_ERROR', String((e as Error).message).slice(0, 500), pgCode) : toSourceError(e)
      if (own && err) err.details = { position: Number((e as { position?: unknown }).position) || null }
      if (!client && err) this.down.set(c.id, { until: Date.now() + CONNECT_BACKOFF_MS, err })
      this.queryLog.record({ started, durationMs, connectionId: c.id, datasetId: o.datasetId ?? null, userId: o.userId ?? null, kind: o.kind, status: aborted ? 'cancelled' : 'error', rows: null, errorCode: err?.code ?? 'CLIENT_ABORTED' })
      if (err) this.log.warn({ connection: c.id, kind: o.kind, durationMs, code: err.code, diagnostic: err.diagnostic }, 'source query failed')
      throw err ?? e
    } finally {
      o.signal?.removeEventListener('abort', onAbort)
      client?.release(broken)
    }
  }

  /** Cancels a running statement of DOD's own session (no superuser needed for one's own backends). */
  private async cancelBackend(c: SourceConnectionConfig, pid: number) {
    try {
      await this.pool(c).query('SELECT pg_cancel_backend($1)', [pid])
      this.log.info({ connection: c.id, pid }, 'source query cancelled (client aborted)')
    } catch (e) {
      this.log.warn({ connection: c.id, code: (e as { code?: string }).code }, 'cancel failed')
    }
  }

  /** Lets the next query try to connect again at once (Test Connection must always really connect). */
  clearBackoff(id: string) {
    this.down.delete(id)
  }

  /** Drops a pool (e.g. after a failed test) so the next attempt reconnects with current settings. */
  async reset(id: string) {
    const p = this.pools.get(id)
    const ch = this.clickhouse.get(id)
    this.down.delete(id)
    this.pools.delete(id)
    this.clickhouse.delete(id)
    await Promise.all([p?.end().catch(() => undefined), ch?.close().catch(() => undefined), ...this.resetHooks.map((h) => h(id).catch(() => undefined))])
  }

  async closeAll() {
    await Promise.all([...this.pools.values()].map((p) => p.end().catch(() => undefined)))
    await Promise.all([...this.clickhouse.values()].map((ch) => ch.close().catch(() => undefined)))
    this.pools.clear()
    this.clickhouse.clear()
    await Promise.all(this.list().map((c) => Promise.all(this.resetHooks.map((h) => h(c.id).catch(() => undefined)))))
  }
}
